import type { MaterialGrade } from "./materials";
import { DEFAULT_PRINT_TEMPERATURE } from "./density";
import { airTemperatureSettings } from "./temperature";
import resolvedConfig from "./profiles/mk4s-standard-0.4-prusa292.ini?raw";
import air85Config from "./profiles/tpu-air-85a-250c.ini?raw";
import air95Config from "./profiles/tpu-air-95a-250c.ini?raw";

const PRINT_PRESET = "Insole Studio - TPU Air - 0.20mm MK4 0.4 START";
const PRINTER_PRESET = "Original Prusa MK4S 0.4 nozzle";

function readIni(text: string, section?: string): Map<string, string> {
  const result = new Map<string, string>();
  let currentSection: string | undefined;
  for (const line of text.split(/\r?\n/)) {
    if (line.startsWith("[")) {
      currentSection = line.slice(1, -1);
      continue;
    }
    if (currentSection !== section || /^[#;]/.test(line)) continue;
    const separator = line.indexOf(" = ");
    if (separator < 0) continue;
    result.set(line.slice(0, separator), line.slice(separator + 3));
  }
  return result;
}

/**
 * Complete, resolved PrusaSlicer 2.9.2 project configuration for the MK4S
 * standard-flow 0.4 mm nozzle. This is intentionally not a config bundle:
 * a 3MF needs the native commented config format and all machine settings,
 * including its start/end G-code, independently of the recipient's presets.
 */
export function buildCompletePrintConfig(
  materialGrade: MaterialGrade,
  temperature = DEFAULT_PRINT_TEMPERATURE,
): string {
  const bundle = materialGrade === "85a" ? air85Config : air95Config;
  const sourcePreset = `Insole Studio - Siraya TPU Air ${materialGrade.toUpperCase()} - 250C foam START`;
  const filamentPreset =
    temperature === 250
      ? sourcePreset
      : `Insole Studio - Siraya TPU Air ${materialGrade.toUpperCase()} - ${temperature}C START`;
  const thermal = airTemperatureSettings(materialGrade, temperature);
  const config = readIni(resolvedConfig);
  const print = readIni(bundle, `print:${PRINT_PRESET}`);
  const filament = readIni(bundle, `filament:${sourcePreset}`);
  if (!print.size || !filament.size) {
    throw new Error("No complete print configuration for this material grade.");
  }

  for (const preset of [print, filament]) {
    for (const [key, value] of preset) {
      // Preset compatibility is serialized cumulatively in a native project.
      if (key !== "compatible_printers_condition") config.set(key, value);
    }
  }
  config.set(
    "compatible_printers_condition_cummulative",
    [print, filament]
      .map((preset) =>
        JSON.stringify(preset.get("compatible_printers_condition")),
      )
      .join(";"),
  );
  // PrusaSlicer serializes these filament properties as string vectors.
  config.set("filament_notes", JSON.stringify(filament.get("filament_notes")));
  config.set("filament_settings_id", JSON.stringify(filamentPreset));
  config.set("print_settings_id", PRINT_PRESET);
  config.set("printer_settings_id", PRINTER_PRESET);
  config.set("default_print_profile", PRINT_PRESET);
  config.set("default_filament_profile", JSON.stringify(filamentPreset));
  config.set("temperature", String(thermal.temperature));
  config.set("first_layer_temperature", String(thermal.temperature));
  config.set("extrusion_multiplier", String(thermal.multiplier));
  if (temperature !== DEFAULT_PRINT_TEMPERATURE) {
    config.set(
      "filament_notes",
      JSON.stringify(
        `${filament.get("filament_notes")} Whole-insole ${temperature} C, starting extrusion multiplier ${thermal.multiplier}. ${thermal.interpolated ? "Flow is linearly interpolated between manufacturer guide points; calibrate before use." : "Flow is a midpoint of the manufacturer's grade-specific starting range; calibrate before use."} Regional temperature targets are not applied by native Prusa modifiers.`,
      ),
    );
  }

  return (
    "; generated by PrusaSlicer 2.9.2\n\n" +
    [...config]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, value]) => `; ${key} = ${value}\n`)
      .join("")
  );
}
